"""
Patch — Domain Model.

Represents a proposed code modification. A Patch is the unit of work
for WRITE and HYBRID execution modes. It is a pure data model — no
filesystem access or Git operations happen here.

The source of truth is always the repository file system. Patches
describe mutations to be applied to those files. Neo4j is NEVER
modified directly by write operations — re-indexing is delegated to
codemind-parser after a successful write.
"""

from __future__ import annotations

from enum import Enum
from typing import List, Optional

from pydantic import BaseModel, Field


class PatchOperation(str, Enum):
    """
    The type of mutation a PatchFile represents.

    Attributes:
        ADD:    A new file is created.
        MODIFY: An existing file is modified.
        DELETE: An existing file is removed.
        RENAME: An existing file is moved to a new path.
    """

    ADD = "ADD"
    MODIFY = "MODIFY"
    DELETE = "DELETE"
    RENAME = "RENAME"


class PatchFile(BaseModel):
    """
    Describes a mutation to a single file within a repository.

    Attributes:
        file_path:     Repository-relative path to the target file.
        operation:     Type of mutation to apply.
        original_path: Original path (only relevant for RENAME operations).
        diff:          Unified diff representing the change.
        content:       Full file content for ADD operations.
        rationale:     LLM-generated explanation for this specific change.
    """

    file_path: str = Field(
        ..., description="Repository-relative path to the target file."
    )
    operation: PatchOperation = Field(
        ..., description="Type of mutation to apply."
    )
    original_path: Optional[str] = Field(
        default=None,
        description="Original path — only relevant for RENAME operations.",
    )
    diff: Optional[str] = Field(
        default=None,
        description="Unified diff representing the change.",
    )
    content: Optional[str] = Field(
        default=None,
        description="Full file content for ADD operations.",
    )
    rationale: Optional[str] = Field(
        default=None,
        description="Explanation for this specific file change.",
    )


class Patch(BaseModel):
    """
    A complete proposed modification to one or more files in a repository.

    A Patch is generated by the Patch Generator node, validated by the
    Validation node, and applied by the Git Operations node. If
    validation fails, the workflow may loop back for re-generation.

    Attributes:
        patch_id:      Unique identifier for this patch.
        repository_id: Repository this patch targets.
        branch:        Target branch for the patch application.
        title:         Short human-readable title for the change.
        description:   Detailed description of the change.
        files:         List of file-level mutations.
        validated:     True if the Validation node has approved this patch.
        validation_errors: List of validation error messages if not validated.
    """

    patch_id: str = Field(..., description="Unique patch identifier.")
    repository_id: str = Field(
        ..., description="Repository this patch targets."
    )
    branch: str = Field(..., description="Target branch for patch application.")
    title: str = Field(..., description="Short human-readable title.")
    description: str = Field(..., description="Detailed change description.")
    files: List[PatchFile] = Field(
        default_factory=list,
        description="File-level mutations in this patch.",
    )
    validated: bool = Field(
        default=False,
        description="True if the Validation node has approved this patch.",
    )
    validation_errors: List[str] = Field(
        default_factory=list,
        description="Validation error messages if not validated.",
    )
